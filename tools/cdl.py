#!/usr/bin/env python3
"""Compare a Mesen code/data log with the build.

usage: tools/cdl.py [CDL] [--report FILE] [--entries FILE]

CDL defaults to fe4.cdl. The log is Mesen 2's CDLv2 format: "CDLv2", the CRC32
of the ROM, then one flag byte per ROM byte. The flags, as checked against the
built source (the report repeats the check each run):

  $01 executed as code        $08 subroutine entry (target of jsr/jsl)
  $02 read as data            $10 executed with 8-bit index registers
  $04 jump or branch target   $20 executed with 8-bit accumulator

The tool builds the repository twice in a temporary copy, with the base ROM
filled with $00 and with $FF, to find the bytes that come from source (the same
method as ./build.sh coverage), and takes a 64tass listing of one of those
builds to tell source instructions from source data. It then reports:

  - executed code that is not built, by bank, and the ways it is reached;
  - raw .long/.word values in built tables that point at that code;
  - built code that is read as a table by an indexed load or jump;
  - built data that is executed;
  - bulk reads of code (checksums and similar);
  - the read extents of the tables in include/Undisassembled.h.

--report writes the report as Markdown (default: print it); when the file
already has the marker line, the text above it is kept. --entries writes
every entry point of executed code that is not built, with its register widths,
as starting points for tools/disasm.py.

Two things in the log are noise: 1-3 byte data marks inside code come from the
emulator's dummy reads, and a single data mark on the first byte of a routine
usually means the table before it is read with 16-bit loads.
"""
import argparse, binascii, datetime, bisect, collections, glob, os, re, struct, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from disasm import OPS, SIZE
from asmlib import read_rom, repo_copy, assemble, errors, find_routines, ROM_PATH, ROM_SIZE

MARKER = '<!-- Everything below is generated by tools/cdl.py. -->'

CODE, DATA, JUMP, SUB, X8, M8 = 0x01, 0x02, 0x04, 0x08, 0x10, 0x20

MNEMONICS = set('''adc and asl bcc bcs beq bge bit blt bmi bne bpl bra brk brl bvc bvs clc
cld cli clv cmp cop cpx cpy dec dex dey eor inc inx iny jml jmp jsl jsr lda ldx ldy lsr mvn
mvp nop ora pea pei per pha phb phd phk php phx phy pla plb pld plp plx ply rep rol ror rti
rtl rts sbc sec sed sei sep sta stp stx sty stz tax tay tcd tcs tdc trb tsb tsc tsx txa txs
txy tya tyx wai wdm xba xce'''.split())

# Indexed reads whose base is a table: abs,x / abs,y (program bank assumed), long,x,
# and jmp/jsr (abs,x), whose table is always in the program bank.
ABS_INDEXED_READS = {0x1D, 0x3D, 0x5D, 0x7D, 0xBD, 0xDD, 0xFD, 0xBC,
                     0x19, 0x39, 0x59, 0x79, 0xB9, 0xD9, 0xF9, 0xBE}
LONG_INDEXED_READS = {0x1F, 0x3F, 0x5F, 0x7F, 0xBF, 0xDF, 0xFF}
INDEXED_JUMPS = {0x7C, 0xFC}

LISTING_RE = re.compile(r'^\.[0-9a-f]+\t([0-9a-f]{6})\t([0-9a-f ]*)\t\s*(\S+)')
DATA_LINE_RE = re.compile(r'^[.>][0-9a-f]+\t([0-9a-f]{6})\t[0-9a-f ]*\t\s*(?:\w+\s+)?\.(long|word)\s+(.*)')


def cpu(o):
    """File offset to the CPU address the code uses ($80-$BF for the upper halves)."""
    bank = (o >> 16) | (0x80 if o & 0x8000 else 0xC0)
    return f'${bank:02X}/{o & 0xFFFF:04X}'


def load_cdl(path):
    raw = open(path, 'rb').read()
    if raw[:5] != b'CDLv2' or len(raw) != 9 + ROM_SIZE:
        raise SystemExit(f'{path}: not a Mesen CDLv2 log for a 4 MB ROM')
    return raw[9:], struct.unpack('<I', raw[5:9])[0]


def build_maps():
    """(built, srccode, listing lines, labels): which bytes come from source, which
    of those are instructions, the listing, and {offset: name} for top-level labels."""
    builds, listing, labels = [], [], {}
    with repo_copy() as tmp:
        for fill in (0x00, 0xFF):
            open(os.path.join(tmp, ROM_PATH), 'wb').write(bytes([fill]) * ROM_SIZE)
            extra = ('-L', 'list.txt', '--no-monitor', '--vice-labels', '-l', 'labels.txt') if fill == 0 else ()
            ok, log = assemble(tmp, f'{fill:02X}.sfc', extra)
            if not ok:
                raise SystemExit('fill build failed:\n' + '\n'.join(errors(log)[:10]))
            builds.append(open(os.path.join(tmp, f'{fill:02X}.sfc'), 'rb').read())
        listing = open(os.path.join(tmp, 'list.txt'), encoding='utf-8', errors='replace').read().split('\n')
        for line in open(os.path.join(tmp, 'labels.txt'), encoding='utf-8'):
            p = line.split()
            if len(p) == 3 and p[0] == 'al' and ':' not in p[2]:
                a = int(p[1], 16)
                if a >= 0x800000:
                    labels.setdefault(a & 0x3FFFFF, p[2].lstrip('.'))
    built = bytes(x == y for x, y in zip(*builds))
    srccode = bytearray(ROM_SIZE)
    for line in listing:
        m = LISTING_RE.match(line) or (re.search(r'; mv[np] ', line) and LISTING_RE.match('.' + line[1:]))
        # Block moves are written as .byte with a "; mvn"/"; mvp" comment.
        if m and (m.group(3).lower().split('.')[0] in MNEMONICS or re.search(r'; mv[np] ', line)):
            o = int(m.group(1), 16) & 0x3FFFFF
            for i in range(len(m.group(2).split())):  # label lines have no bytes
                srccode[o + i] = 1
    return built, bytes(srccode), listing, labels


def runs(pred, lo=0, hi=ROM_SIZE, gap=0):
    """[(start, end)] of offsets where pred holds, merging runs at most gap apart."""
    out, start, last = [], None, None
    for o in range(lo, hi):
        if pred(o):
            if start is None:
                start = o
            elif o - last > gap + 1:
                out.append((start, last + 1))
                start = o
            last = o
    if start is not None:
        out.append((start, last + 1))
    return out


class Analysis:
    def __init__(self, cdl, rom, built, srccode, listing, labels):
        self.c, self.rom, self.built, self.sc = cdl, rom, built, srccode
        self.listing, self.labels = listing, labels
        self.keys = sorted(labels)
        self.out = []

    # helpers
    def near(self, o, quote='`'):
        i = bisect.bisect_right(self.keys, o) - 1
        if i < 0:
            return '?'
        k = self.keys[i]
        return f'{quote}{self.labels[k]}{quote}' + (f'+${o - k:X}' if o != k else '')

    def code(self, o):
        return self.c[o] & CODE

    def unbuilt_code(self, o):
        return self.c[o] & CODE and not self.built[o]

    def widths(self, o):
        f = self.c[o]
        return ('8' if f & M8 else '16') + '/' + ('8' if f & X8 else '16')

    def p(self, *lines):
        self.out.extend(lines)

    def table(self, header, rows):
        self.p('| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header))
        for r in rows:
            self.p('| ' + ' | '.join(str(x) for x in r) + ' |')
        self.p('')

    def instruction_starts(self):
        """bytearray marking the first byte of every executed instruction.

        Mesen marks every byte of an executed instruction as code and keeps the
        register widths on its first byte, so decoding forward from the first byte
        of each executed run, and from every jump or entry mark, finds them all.
        """
        if hasattr(self, '_starts'):
            return self._starts
        c, rom = self.c, self.rom
        starts = bytearray(ROM_SIZE)
        for o in range(ROM_SIZE):
            if not c[o] & CODE or starts[o]:
                continue
            if o and c[o - 1] & CODE and not c[o] & (SUB | JUMP):
                continue
            pc = o
            while pc < ROM_SIZE and c[pc] & CODE and not (starts[pc] and pc != o):
                mode = OPS[rom[pc]][1]
                n = 1 + (1 if mode == 'immm' and c[pc] & M8 else 1 if mode == 'immx' and c[pc] & X8
                         else SIZE[mode])
                if not all(c[pc + i] & CODE for i in range(n)):
                    break
                starts[pc] = 1
                pc += n
        self._starts = starts
        return starts

    def executed_ops(self, opcodes, length=None):
        """Offsets of executed instructions with one of these opcodes."""
        starts, rom = self.instruction_starts(), self.rom
        for o in range(ROM_SIZE - 4):
            if starts[o] and rom[o] in opcodes:
                yield o

    # sections
    def header(self, path, crc):
        rom_crc = binascii.crc32(self.rom) & 0xFFFFFFFF
        c, built, sc = self.c, self.built, self.sc
        self.p('## Generated report', '',
               f'Generated by `tools/cdl.py {path}` on {datetime.date.today().isoformat()}; do not edit. Addresses are CPU addresses; code uses the `$80`-`$BF` '
               'mirror. "Built" means the byte comes from source (the method of `./build.sh coverage`).', '')
        self.p('### The log', '')
        self.p(f'- CRC32 in the log `{crc:08X}`, ROM `{rom_crc:08X}`: '
               + ('they match.' if crc == rom_crc else '**they differ; the log is from another ROM.**'))
        # flag check 1: directly jsl'd routines carry $08
        jsl_targets = set()
        for o in self.executed_ops({0x22}, 4):
            jsl_targets.add((self.rom[o + 1] | self.rom[o + 2] << 8 | self.rom[o + 3] << 16) & 0x3FFFFF)
        routines = [o for o, n in self.labels.items() if n[:2] in ('rl', 'rs') and c[o] & CODE]
        called = [o for o in routines if o in jsl_targets]
        with_sub = sum(1 for o in called if c[o] & SUB)
        self.p(f'- Flag `$08` is the subroutine entry mark: {with_sub} of the {len(called)} built routines '
               'that executed code reaches with a direct `jsl` carry it.')
        # flag check 2: widths at routine starts vs the source's .as/.xs
        agree = total = 0
        disagree = []
        # (the listing leaves out directives, so this reads the source files)
        for path in glob.glob('engine/**/*.asm', recursive=True):
            lines = open(path, encoding='utf-8').read().split('\n')
            for i, name, addr in find_routines(lines):
                o = addr & 0x3FFFFF
                if not name.startswith('r') or not c[o] & CODE:
                    continue
                head = []
                for l in lines[i + 1:i + 8]:
                    s = l.strip()
                    if s and not s.startswith(('.', ';')):
                        break
                    head.append(s)
                for flag, small, large in ((M8, '.as', '.al'), (X8, '.xs', '.xl')):
                    if small in head or large in head:
                        total += 1
                        if (small in head) == bool(c[o] & flag):
                            agree += 1
                        else:
                            disagree.append((o, name, small if small in head else large))
        self.p(f'- Flags `$20` and `$10` are 8-bit accumulator and index: they agree with the `.as`/`.al` and '
               f'`.xs`/`.xl` at {agree} of {total} executed routine starts that state a width.')
        if disagree:
            self.p('', 'Where they disagree, the routine was last entered with other widths than the source '
                   'assumes. That is harmless when it saves or sets the widths before they matter (`php`, '
                   '`rep` or `sep` in its first 4 bytes); otherwise check its callers.', '')
            def sets_widths(o):
                return any(self.rom[o + i] in (0x08, 0xC2, 0xE2) for i in range(4))
            self.table(['Routine', 'Name', 'Source says', 'Log says A/X', 'Sets widths first'],
                       [[cpu(o), f'`{n}`', f'`{d}`', self.widths(o), 'yes' if sets_widths(o) else '**no**']
                        for o, n, d in sorted(disagree)])
        self.p('- So: `$01` code, `$02` data, `$04` jump target, `$08` subroutine entry, `$10` 8-bit X, '
               '`$20` 8-bit A.', '')

        cats = collections.Counter()
        for o in range(ROM_SIZE):
            f = c[o]
            cats[('code' if f & CODE else 'data' if f & DATA else 'none', bool(built[o]))] += 1
        code_all = cats[('code', True)] + cats[('code', False)]
        data_all = cats[('data', True)] + cats[('data', False)]
        self.table(['Bytes', 'In the log', 'Built', 'Not built'], [
            ['Executed', f'{code_all:,}', f'{cats[("code", True)]:,}', f'**{cats[("code", False)]:,}**'],
            ['Read only', f'{data_all:,}', f'{cats[("data", True)]:,}', f'{cats[("data", False)]:,}'],
            ['Untouched', f'{cats[("none", True)] + cats[("none", False)]:,}', f'{cats[("none", True)]:,}',
             f'{cats[("none", False)]:,}'],
        ])

    def unbuilt_code_section(self):
        c = self.c
        self.p('### Executed code that is not built', '')
        per_bank = collections.Counter()
        entries = collections.Counter()
        for o in range(ROM_SIZE):
            if self.unbuilt_code(o):
                per_bank[o >> 16] += 1
                if c[o] & (SUB | JUMP):
                    entries[o >> 16] += 1
        total = sum(per_bank.values())
        self.p(f'{total:,} bytes. Nothing in the build calls them directly (the tracer checks that); they '
               'are reached through pointers, computed jumps and other unbuilt code.', '')
        self.table(['Bank', 'Bytes', 'Entry points'],
                   [[f'`${(b | 0x80):02X}`', f'{n:,}', entries[b]] for b, n in per_bank.most_common()])
        rs = runs(self.unbuilt_code, gap=16)
        big = sorted(rs, key=lambda r: -sum(1 for o in range(*r) if c[o] & CODE))[:25]
        self.p(f'{len(rs)} runs (gaps of up to 16 bytes merged). The largest:', '')
        self.table(['Start', 'End', 'Executed bytes', 'Entry widths A/X', 'After'],
                   [[cpu(s), cpu(e - 1), sum(1 for o in range(s, e) if c[o] & CODE),
                     self.widths(s), self.near(s)] for s, e in sorted(big)])

    def raw_pointer_section(self):
        """Raw numbers in built .long/.word directives that point at executed unbuilt code."""
        self.p('### Raw pointers in built tables that lead to unbuilt code', '',
               'Values written as numbers in `.long` (any bank) or `.word` (same bank, entry points only) '
               'directives whose target is executed code that is not built. Writing them as labels gives '
               '`tools/trace.py` new starting points.', '')
        c = self.c
        hits = collections.defaultdict(list)
        for line in self.listing:
            m = DATA_LINE_RE.match(line)
            if not m:
                continue
            o = int(m.group(1), 16) & 0x3FFFFF
            if not self.built[o]:
                continue
            size = 3 if m.group(2) == 'long' else 2
            # Only items that are a bare number: not expressions such as ($8000 >> 1).
            items = [i.strip() for i in m.group(3).split(';')[0].split(',')]
            for tok in [mm.group(1) for i in items if (mm := re.fullmatch(r'(?:<>)?\$([0-9A-Fa-f]+)', i))]:
                if len(tok) != size * 2:
                    continue
                v = int(tok, 16)
                t = (v & 0x3FFFFF) if size == 3 else ((o & 0x3F0000) | v)
                if size == 3 and v < 0x800000:
                    continue
                if size == 2 and (v < 0x8000 or not c[t] & (SUB | JUMP)):
                    continue
                if self.unbuilt_code(t):
                    i = bisect.bisect_right(self.keys, o) - 1
                    hits[self.keys[i]].append(t)
        rows = []
        for k, ts in sorted(hits.items(), key=lambda kv: -len(kv[1])):
            sample = ', '.join(cpu(t) for t in ts[:4]) + (' ...' if len(ts) > 4 else '')
            rows.append([f'`{self.labels[k]}` ({cpu(k)})', len(ts), sample])
        if rows:
            self.table(['Table', 'Pointers to unbuilt code', 'Targets'], rows)
        else:
            self.p('None.', '')

    def tables_as_code_section(self):
        """Built instructions that executed code reads as a table."""
        self.p('### Built code that is read as a table', '',
               'Built instructions at the base of an indexed read (`lda table,x`, `lda long,x`, '
               '`jsr (table,x)`, ...) from executed code, where the log shows reads and no execution. '
               'These are tables that were disassembled as code. For `abs,x` reads the data bank is assumed '
               'to be the program bank.', '')
        c, rom, sc = self.c, self.rom, self.sc
        found = {}
        def check(base, reader, kind):  # base must be built as an instruction and read, not executed
            if not (0 <= base < ROM_SIZE) or not sc[base]:
                return
            if not c[base] & DATA or c[base] & CODE:
                return
            for b in found:
                if b - 8 < base < b + 8:  # the same table read at a small offset
                    found[b][0].add(reader)
                    return
            read = sum(1 for o in range(base, min(base + 64, ROM_SIZE)) if c[o] & DATA and not c[o] & CODE)
            found[base] = ({reader}, kind, read)
        for o in self.executed_ops(ABS_INDEXED_READS | INDEXED_JUMPS, 3):
            base = (o & 0x3F0000) | rom[o + 1] | rom[o + 2] << 8
            if rom[o + 2] >= 0x80:
                check(base, o, 'jump table' if rom[o] in INDEXED_JUMPS else 'abs indexed')
        for o in self.executed_ops(LONG_INDEXED_READS, 4):
            if rom[o + 3] >= 0x80:
                check((rom[o + 1] | rom[o + 2] << 8 | rom[o + 3] << 16) & 0x3FFFFF, o, 'long indexed')
        if found:
            self.table(['Table', 'Read by', 'Kind', 'Bytes read in first 64'],
                       [[f'{cpu(b)} {self.near(b)}', ', '.join(cpu(x) for x in sorted(r)), k, n]
                        for b, (r, k, n) in sorted(found.items())])
        else:
            self.p('None.', '')

    def data_executed_section(self):
        self.p('### Built data that is executed', '',
               'Bytes built as data directives that the log shows executed. "How entered" is the mark on '
               'the first executed byte; `pea` means an executed `pea #start-1` pushes it as a return '
               'address.', '')
        c, rom = self.c, self.rom
        pea_returns = {}
        for o in self.executed_ops({0xF4}, 3):
            pea_returns[(o & 0x3F0000) | ((rom[o + 1] | rom[o + 2] << 8) + 1) & 0xFFFF] = o
        rows = []
        for s, e in runs(lambda o: c[o] & CODE and self.built[o] and not self.sc[o], gap=2):
            f = c[s]
            how = 'subroutine entry' if f & SUB else 'jump target' if f & JUMP else 'falls through'
            if s in pea_returns:
                how = f'`pea` at {cpu(pea_returns[s])}'
            rows.append([cpu(s), e - s, self.widths(s), how, self.near(s)])
        self.table(['Start', 'Bytes', 'Widths A/X', 'How entered', 'In'], rows) if rows else self.p('None.', '')

    def bulk_read_section(self):
        self.p('### Code read as data in bulk', '',
               'Runs of data reads of at least 8 bytes over code (executed or built as instructions). Dummy '
               'reads are shorter, so these are deliberate reads: checksums, copies to RAM, or tables that '
               'were disassembled as code.', '')
        c, sc = self.c, self.sc
        rows = []
        for s, e in runs(lambda o: c[o] & DATA):
            n_sc = sum(sc[s:e])
            n_cd = sum(1 for o in range(s, e) if c[o] & CODE)
            if n_sc >= 8 or n_cd >= 8:
                rows.append([cpu(s), cpu(e - 1), e - s, n_cd, n_sc, sum(self.built[s:e]), self.near(s)])
        self.table(['Start', 'End', 'Bytes', 'Executed', 'Built as code', 'Built', 'In'], rows)

    def head_reads_section(self):
        c, sc = self.c, self.sc
        rows = []
        for o, n in sorted(self.labels.items()):
            if n[:2] in ('rl', 'rs') and sc[o] and c[o] & DATA and not c[o] & CODE:
                prev = c[o - 1] & DATA and not sc[o - 1]
                rows.append([cpu(o), f'`{n}`', 'yes' if prev else 'no',
                             'yes' if any(c[o + i] & CODE for i in range(1, 8)) else 'no'])
        self.p('### Routines whose first byte is only read', '',
               'Built routines whose first byte is read but never executed. When the byte before it is a '
               'read data byte, a 16-bit read of the last entry of that table explains it and the routine '
               'is fine; otherwise look at it.', '')
        self.table(['Routine', 'Name', 'Previous byte is read data', 'Executed later'], rows)

    def undisassembled_section(self):
        self.p('### Tables in include/Undisassembled.h', '',
               'For each table, the gap up to the next label or built byte, and what the log read in it. '
               'The log only shows what the prologue read, so these are lower bounds; "From start" is the '
               'unbroken run of reads from the first byte.', '')
        und = []
        for line in open('include/Undisassembled.h', encoding='utf-8'):
            m = re.match(r'\s*(a\w+)\s*:\?=\s*address\(\$([0-9A-Fa-f]{6})\)\s*;?\s*(.*)', line)
            if m:
                und.append((int(m.group(2), 16) & 0x3FFFFF, m.group(1), m.group(2).upper()))
        bounds = sorted(set(self.keys) | {o for o, _, _ in und})
        c = self.c
        rows = []
        for o, name, written in sorted(und):
            j = bisect.bisect_right(bounds, o)
            nxt = bounds[j] if j < len(bounds) else ROM_SIZE
            e = o
            while e < nxt and not self.built[e]:
                e += 1
            read = [k for k in range(o, e) if c[k] & DATA and not c[k] & CODE]
            run = 0
            while o + run < e and c[o + run] & DATA:
                run += 1
            executed = sum(1 for k in range(o, e) if c[k] & CODE)
            rows.append([f'`{name}`', f'${written[:2]}/{written[2:]}', f'${e - o:X}', f'${len(read):X}', f'${run:X}',
                         f'+${read[-1] - o:X}' if read else '-', executed or ''])
        self.table(['Table', 'Address', 'Gap', 'Bytes read', 'From start', 'Last read', 'Executed in gap'],
                   rows)

    def entries(self):
        """Lines for --entries: every entry point of executed unbuilt code."""
        c, rom = self.c, self.rom
        calls = collections.defaultdict(list)
        for op, n in ((0x22, 4), (0x5C, 4)):
            for o in self.executed_ops({op}, n):
                calls[(rom[o + 1] | rom[o + 2] << 8 | rom[o + 3] << 16) & 0x3FFFFF].append(o)
        for op in (0x20, 0x4C):
            for o in self.executed_ops({op}, 3):
                calls[(o & 0x3F0000) | rom[o + 1] | rom[o + 2] << 8].append(o)
        lines = ['# Entry points of executed code that is not built (tools/cdl.py).',
                 '# address  kind  A/X  callers  location']
        for o in range(ROM_SIZE):
            if self.unbuilt_code(o) and c[o] & (SUB | JUMP):
                kind = 'sub ' if c[o] & SUB else 'jump'
                who = ','.join(cpu(r) for r in calls.get(o, [])[:3]) or '-'
                lines.append(f'{cpu(o)}  {kind}  {self.widths(o):5s}  {who}  {self.near(o, '')}')
        return lines


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('cdl', nargs='?', default='fe4.cdl')
    ap.add_argument('--report', help='write the Markdown report here (default: print it)')
    ap.add_argument('--entries', help='write the unbuilt entry points here')
    args = ap.parse_args()
    cdl, crc = load_cdl(args.cdl)
    print('building the source maps...', file=sys.stderr)
    built, srccode, listing, labels = build_maps()
    a = Analysis(cdl, read_rom(), built, srccode, listing, labels)
    print('analysing...', file=sys.stderr)
    a.header(args.cdl, crc)
    a.unbuilt_code_section()
    a.raw_pointer_section()
    a.tables_as_code_section()
    a.data_executed_section()
    a.bulk_read_section()
    a.head_reads_section()
    a.undisassembled_section()
    text = '\n'.join(a.out).rstrip('\n') + '\n'
    if args.report:
        # Keep anything written by hand above the marker.
        old = open(args.report, encoding='utf-8').read() if os.path.exists(args.report) else ''
        if MARKER in old:
            text = old[:old.index(MARKER)] + MARKER + '\n\n' + text
        open(args.report, 'w', encoding='utf-8').write(text)
    else:
        sys.stdout.write(text)
    if args.entries:
        open(args.entries, 'w', encoding='utf-8').write('\n'.join(a.entries()) + '\n')


if __name__ == '__main__':
    main()
